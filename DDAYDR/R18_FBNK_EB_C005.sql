SET 'auto.offset.reset' = 'earliest';
SET 'ksql.streams.num.stream.threads' = '8';

-- ============================================================
-- DROP TABLE/STREAM
-- ============================================================

DROP STREAM IF EXISTS DDAYDR_R18_FBNK_EB_C005_EXPLODED DELETE TOPIC;
DROP STREAM IF EXISTS DDAYDR_R18_FBNK_EB_C005_MAPPED DELETE TOPIC;
DROP STREAM IF EXISTS DDAYDR_R18_FBNK_EB_C005_PARSED DELETE TOPIC;
DROP STREAM IF EXISTS DDAYDR_R18_FBNK_EB_C005_RAW;

-- ============================================================
-- DDAYDR_R18_FBNK_EB_C005_RAW
-- ============================================================

CREATE OR REPLACE STREAM DDAYDR_R18_FBNK_EB_C005_RAW (
    RECID      STRING,
    OP_TYPE    STRING,
    POS        STRING,
    OP_TS      STRING,
    CURRENT_TS STRING,
    XMLRECORD  STRING
) WITH (
    KAFKA_TOPIC = 'DDAYDR_R18.FBNK_EB_C005_RAW',
    FORMAT      = 'AVRO'
);

-- ============================================================
-- DDAYDR_R18_FBNK_EB_C005_PARSED
-- ============================================================

CREATE OR REPLACE STREAM DDAYDR_R18_FBNK_EB_C005_PARSED
WITH (
    KAFKA_TOPIC = 'DDAYDR_R18.FBNK_EB_C005_PARSED'
) AS
SELECT
    ROWKEY,
    RECID,
    OP_TYPE,
    POS,
    PARSE_TIMESTAMP(OP_TS, 'yyyy-MM-dd HH:mm:ss.SSSSSS')      AS COMMIT_TS,
    PARSE_TIMESTAMP(CURRENT_TS, 'yyyy-MM-dd HH:mm:ss.SSSSSS') AS REPLICAT_TS,
    PARSE_T24_RECORD(XMLRECORD, 6232)                         AS DATA -- R18.SS_EB_CONTRACT_BALANCES
FROM DDAYDR_R18_FBNK_EB_C005_RAW
EMIT CHANGES;

-- ============================================================
-- DDAYDR_R18_FBNK_EB_C005_MAPPED
-- ============================================================

CREATE OR REPLACE STREAM DDAYDR_R18_FBNK_EB_C005_MAPPED
WITH (
    KAFKA_TOPIC = 'DDAYDR_R18.FBNK_EB_C005_MAPPED'
) AS
SELECT
    ROWKEY,
    RECID,
    OP_TYPE,
    POS,
    COMMIT_TS,
    REPLICAT_TS,
    PARSE_TIMESTAMP(
        TIMESTAMPTOSTRING(UNIX_TIMESTAMP(), 'yyyy-MM-dd HH:mm:ss.SSSSSS'),
        'yyyy-MM-dd HH:mm:ss.SSSSSS'
    ) AS MAPPED_TS,
    DATA['CURRENCY']         AS CURRENCY,
    DATA['APPLICATION']      AS APPLICATION,
    DATA['CUSTOMER']         AS CUSTOMER,
    DATA['DATE_LAST_UPDATE'] AS DATE_LAST_UPDATE,
    DATA['HVT_FLAG']         AS HVT_FLAG,
    EXPLODE_ASSET_BALANCES(
        DATA['CURR_ASSET_TYPE'],
        DATA['OPEN_BALANCE'],
        DATA['DEBIT_MVMT'],
        DATA['CREDIT_MVMT'],
        DATA['TYPE_SYSDATE'],
        '20261107'
    ) AS BALANCE,
    DATA['CURR_ASSET_TYPE']  AS CURR_ASSET_TYPE,
    DATA['OPEN_BALANCE']     AS OPEN_BALANCE,
    DATA['DEBIT_MVMT']       AS DEBIT_MVMT,
    DATA['CREDIT_MVMT']      AS CREDIT_MVMT,
    DATA['TYPE_SYSDATE']     AS TYPE_SYSDATE
FROM DDAYDR_R18_FBNK_EB_C005_PARSED
WHERE DATA['CURR_ASSET_TYPE'] IS NOT NULL
EMIT CHANGES;

-- ============================================================
-- DDAYDR_R18_FBNK_EB_C005_EXPLODED
-- ============================================================

CREATE OR REPLACE STREAM DDAYDR_R18_FBNK_EB_C005_EXPLODED
WITH (
    KAFKA_TOPIC = 'DDAYDR_R18.FBNK_EB_C005_EXPLODED'
) AS
SELECT
    ROWKEY,
    RECID,
    BALANCE->ASSET_TYPE AS ASSET_TYPE,
    OP_TYPE,
    POS,
    COMMIT_TS,
    REPLICAT_TS,
    MAPPED_TS,
    PARSE_TIMESTAMP(
        TIMESTAMPTOSTRING(UNIX_TIMESTAMP(), 'yyyy-MM-dd HH:mm:ss.SSSSSS'),
        'yyyy-MM-dd HH:mm:ss.SSSSSS'
    ) AS EXPLODED_TS,
    CURRENCY,
    APPLICATION,
    CUSTOMER,
    DATE_LAST_UPDATE,
    HVT_FLAG,
    BALANCE->OPEN_BAL   AS OPEN_BAL,
    BALANCE->DR_MVT     AS DR_MVT,
    BALANCE->CR_MVT     AS CR_MVT,
    BALANCE->CLOSE_BAL  AS CLOSE_BAL,
    CURR_ASSET_TYPE,
    OPEN_BALANCE,
    DEBIT_MVMT,
    CREDIT_MVMT,
    TYPE_SYSDATE
FROM DDAYDR_R18_FBNK_EB_C005_MAPPED
EMIT CHANGES;
